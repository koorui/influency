def project_indicators(project_id):
    rows = []
    for n, (sources, branch, name, question, requirements) in enumerate(PROJECT_SPECS.get(project_id, []), 1):
        rows.append({'indicator_id':f'{project_id}.{n:02}', 'branch_id':branch, 'name':name,
                     'question':question, 'measurement':question.rstrip('？')+'；按统一分支的对照、范围和归因要求逐项记录。',
                     'evidence_requirements':requirements.split('；'), 'boundary':POLICY['threshold'],
                     'source_metric_ids':sources.split('|'), 'change':'合并修订' if '|' in sources else '保留修订',
                     'scope':'仅用于与本项任务和成果类型相符的成果。'})
    for n, (branch,name,question,requirements) in enumerate(NEW_PROJECT_SPECS.get(project_id, []),1):
        rows.append({'indicator_id':f'{project_id}.N{n:02}', 'branch_id':branch,'name':name,'question':question,
                     'measurement':question.rstrip('？')+'；报告分条件结果与失败情况。',
                     'evidence_requirements':requirements.split('；'),'boundary':'没有相应测试时标记本轮未体现，不从其他对象外推。',
                     'source_metric_ids':[], 'change':'新增', 'scope':'适用于存在相应迁移或边界问题的成果。'})
    return rows


def criteria_for_dimension(project_id, dimension_id, outcome_id=None):
    rows = []
    for n, (branch,name,question,measurement,requirements,boundary) in enumerate(COMMON_SPECS,1):
        rows.append({'indicator_id':f'C{n:02}', 'branch_id':branch,'name':name,'question':question,
                     'measurement':measurement,'evidence_requirements':requirements.split('；'),'boundary':boundary,
                     'source_metric_ids':[], 'change':'细化补充', 'scope':'通用检查项；须结合成果类型与评价范围说明适用性。'})
    professional = project_indicators(project_id)
    if outcome_id is not None:
        professional = [row for row in professional if outcome_id in PROJECT_OUTCOME_SCOPE.get(project_id,{}).get(row['indicator_id'],[])]
    return copy.deepcopy([row for row in [*rows,*professional] if row['branch_id'].split('.')[0] == dimension_id])


def replacement_for(project_id, metric_id):
    return next((row for row in project_indicators(project_id) if metric_id in row['source_metric_ids']), None)


def build_indicator_tree(workspace, dimensions, branches, prepared=None):
    pid = str((workspace.get('project_profile') or {}).get('project_id') or '')
    all_rows = [row for d in dimensions for row in criteria_for_dimension(pid,d['question_id'])]
    bindings = (workspace.get('evidence_adapter') or {}).get('professional_metric_bindings') or []
    old = {r['metric']['metric_id']:r for r in bindings}
    material_rows = (prepared or {}).get('records') or []
    for row in all_rows:
        row['outcome_ids'] = PROJECT_OUTCOME_SCOPE.get(pid,{}).get(row['indicator_id'],[])
        links = [old[mid] for mid in row['source_metric_ids'] if mid in old]
        # Only previously reviewed direct passages count as related. No new search is inferred.
        sources = {item['evidence_id'] for link in links for item in link['metric']['evidence_preview']}
        row['related_material_count'] = len(sources)
        row['material_status'] = '有相关材料，仍需逐项核验' if sources else '所需依据待逐项核对'
        direct, references = [], []
        for material in material_rows:
            if row['outcome_ids'] and material['outcome_ids'] and not set(row['outcome_ids']).intersection(material['outcome_ids']):
                continue
            own_source = any(source_id in material['original_id'].split('|') for source_id in sources)
            common = row['indicator_id'].startswith('C')
            branch_match = row['branch_id'] in material['branch_ids']
            if material['outcome_ids'] and (own_source or (common and branch_match)):
                direct.append(material['record_id'])
            elif branch_match or row['branch_id'].split('.')[0] in material['dimension_ids']:
                references.append(material['record_id'])
            elif row['branch_id']=='D2.3' and material['kind'] in {'贡献拆解材料','归因核验记录'}:
                references.append(material['record_id'])
        row['material_ids'], row['reference_material_ids'] = direct, references
        row['related_material_count'] = len(direct)
        row['material_status'] = '已接入相关材料，内容与适用范围仍需核验' if direct else '已有分支参考，具体判定依据待核对' if references else '所需依据待逐项核对'
    decisions = []
    for mid, link in old.items():
        replacement = replacement_for(pid, mid)
        decisions.append({'original_id':mid,'original_name':link['metric']['metric_name'],
                          'action':replacement['change'] if replacement else '移除',
                          'replacement_id':replacement['indicator_id'] if replacement else '',
                          'replacement_name':replacement['name'] if replacement else '',
                          'reason':RETIRED.get(pid,{}).get(mid) or '保留有效评价问题，按任务、对照与适用范围修订；重复项合并。'})
    return {'version':POLICY['version'], 'project_id':pid,'project_name':(workspace.get('project_profile') or {}).get('project_name') or pid,
            'policy':copy.deepcopy(POLICY),'dimensions':copy.deepcopy(dimensions),'branches':copy.deepcopy(branches),
            'indicators':all_rows,'decisions':decisions,
            'material_registry':{r['record_id']:copy.deepcopy(r) for r in material_rows},
            'upstream_import':copy.deepcopy((prepared or {}).get('upstream_import') or {}),
            'counts':{'dimensions':len(dimensions),'branches':len(branches),'common':len(COMMON_SPECS),
                      'project':len(project_indicators(pid)), 'removed':sum(r['action']=='移除' for r in decisions),
                      'merged_sources':sum(len(r['source_metric_ids'])-1 for r in project_indicators(pid) if len(r['source_metric_ids'])>1),
                      'new_project':len(NEW_PROJECT_SPECS.get(pid,[]))}}
